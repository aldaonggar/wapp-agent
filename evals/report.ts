// npm run eval:report — evals/results/*.json → EVALS.md. Plain Node (type stripping); works with any number of result files.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { JOBS } from "../src/models.ts";
import type { EvalConfig, ScenarioResult } from "./harness";

interface Run { tag: string; config: EvalConfig; at: string; scenarios: ScenarioResult[] }
type Job = "reply" | "extract" | "derive";

const DIR = "evals/results";
const runs: Run[] = existsSync(DIR) ? readdirSync(DIR).filter((f) => f.endsWith(".json")).sort().map((f) => JSON.parse(readFileSync(`${DIR}/${f}`, "utf8"))) : [];
const CATEGORIES = ["short-term", "long-term", "derived", "judgement", "forget", "isolation"];
const JOB_CATEGORIES: Record<Job, string[]> = { reply: ["short-term"], extract: ["long-term", "judgement"], derive: ["derived"] };
const NOT_RUN = "not run";

const model = (r: Run, job: Job) => r.config[job] || JOBS[job].default;
// Default configuration, optionally with one job swapped and memory or retrieval changed.
const isDefault = (r: Run, o: { memory?: boolean; retrieval?: string; except?: Job } = {}) =>
  r.config.memory === (o.memory ?? true) && r.config.retrieval === (o.retrieval ?? "hybrid") && !r.config.effort &&
  (["reply", "extract", "derive"] as const).every((j) => j === o.except || model(r, j) === JOBS[j].default);
const agent = runs.find((r) => isDefault(r));
const baseline = runs.find((r) => isDefault(r, { memory: false }));
const cosine = runs.find((r) => isDefault(r, { retrieval: "cosine" }));
const runFor = (job: Job, id: string) => (id === JOBS[job].default ? agent : runs.find((r) => isDefault(r, { except: job }) && model(r, job) === id));

const score = (xs: ScenarioResult[]) => xs.length ? `${xs.filter((s) => s.passed).length}/${xs.length} (${Math.round((100 * xs.filter((s) => s.passed).length) / xs.length)}%)` : NOT_RUN;
const inCats = (r: Run | undefined, cats: string[]) => r?.scenarios.filter((s) => cats.includes(s.category)) ?? [];
const pct = (xs: number[], p: number) => [...xs].sort((a, b) => a - b)[Math.max(0, Math.ceil((p / 100) * xs.length) - 1)];
const lat = (scs: ScenarioResult[], key: string) => {
  const xs = scs.flatMap((s) => s.turns.map((t) => t[key])).filter((x): x is number => typeof x === "number");
  return xs.length ? `${pct(xs, 50)} / ${pct(xs, 95)}` : "–";
};
const turnsOf = (scs: ScenarioResult[]) => scs.reduce((n, s) => n + s.turns.length, 0);
const per1000 = (scs: ScenarioResult[], job: string) => {
  const cost = scs.reduce((c, s) => c + (s.costByJob?.[job] ?? 0), 0), n = turnsOf(scs);
  return n ? `$${((cost / n) * 1000).toFixed(2)}` : "–";
};
const table = (head: string[], rows: string[][]) => [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
const latencyCols = ["ttft p50 / p95 ms", "first bubble p50 / p95 ms", "total p50 / p95 ms"];
const latency = (scs: ScenarioResult[]) => [lat(scs, "ttft_ms"), lat(scs, "ttfb_ms"), lat(scs, "total_ms")];

const out: string[] = [
  "# Evals",
  "",
  `Generated by \`npm run eval:report\` from ${runs.length} result file(s) in \`${DIR}/\`${runs.length ? "" : " (none yet: the scenarios have not run; `npm run eval` needs `OPENROUTER_API_KEY`, `CLOUDFLARE_API_TOKEN` and `CLOUDFLARE_ACCOUNT_ID`)"}. A scenario passes when every probe is judged correct and every check holds. Latency is wall-clock per reply turn; cost is the price-table cost of the logged model calls, with the judge's calls shown separately.`,
  "",
  "## Results",
  "",
  table(["Category", "Baseline (no memory)", "This agent"], [
    ...CATEGORIES.map((c) => [c, score(inCats(baseline, [c])), score(inCats(agent, [c]))]),
    ["all", score(baseline?.scenarios ?? []), score(agent?.scenarios ?? [])],
  ]),
  "",
  "## Model comparison per job",
  "",
  "Each candidate runs with the other jobs at their defaults, on the categories its job affects. Cost is that job's model calls per 1,000 reply turns.",
];
for (const job of ["reply", "extract", "derive"] as const) {
  const cats = JOB_CATEGORIES[job];
  const rows = JOBS[job].candidates.flatMap((id) => {
    const scs = inCats(runFor(job, id), cats);
    return scs.length ? [[id + (id === JOBS[job].default ? " (default)" : ""), score(scs), ...latency(scs), per1000(scs, job)]] : [];
  });
  out.push("", `### ${job} (${cats.join(", ")})`, "", rows.length ? table(["Model", "Passed", ...latencyCols, `${job} cost / 1,000 replies`], rows) : `${NOT_RUN}.`);
}

const groups = new Map<string, ScenarioResult[]>();
for (const r of runs) {
  const key = `${model(r, "reply")} | ${r.config.effort ?? "lowest"} | ${r.config.memory ? "on" : "off"}`;
  groups.set(key, [...(groups.get(key) ?? []), ...r.scenarios]);
}
out.push("", "## Latency per reply model and effort", "",
  groups.size ? table(["Reply model", "Effort", "Memory", "Turns", ...latencyCols], [...groups].map(([k, scs]) => [...k.split(" | "), String(turnsOf(scs)), ...latency(scs)])) : `${NOT_RUN}.`);

out.push("", "## Candidates not run", "");
for (const job of ["reply", "extract", "derive"] as const) {
  const missing = JOBS[job].candidates.filter((id) => !inCats(runFor(job, id), JOB_CATEGORIES[job]).length);
  out.push(`- ${job}: ${missing.length ? missing.join(", ") : "none"}`);
}
out.push(`- vision: ${JOBS.vision.candidates.join(", ")} (no separate comparison run; the photo scenario uses the reply model, or the vision default when the reply model is text-only)`);

const names = cosine?.scenarios.map((s) => s.name) ?? [];
out.push("", "## Retrieval: cosine vs hybrid", "", cosine
  ? table(["Retrieval", "Passed", "Scenarios"], [
    ["cosine", score(cosine.scenarios), names.join(", ")],
    ["hybrid", score(agent?.scenarios.filter((s) => names.includes(s.name)) ?? []), names.join(", ")],
  ])
  : `${NOT_RUN}.`);

out.push("", "## Transcripts", "", "Times are UTC on the fake clock (the test numbers' zone is America/New_York); filled history is one line.");
if (!runs.length) out.push("", `${NOT_RUN}.`);
for (const r of [agent, baseline, ...runs.filter((x) => x !== agent && x !== baseline)].filter((x): x is Run => !!x)) {
  const sum = (f: (s: ScenarioResult) => number | undefined) => r.scenarios.reduce((c, s) => c + (f(s) ?? 0), 0).toFixed(4); // older result files lack judgeCostUsd
  out.push("", `### ${r.tag}`, "", `Run at ${r.at}; ${score(r.scenarios)} passed; cost $${sum((s) => s.costUsd)}; judge cost $${sum((s) => s.judgeCostUsd)}.`);
  for (const s of r.scenarios) {
    out.push("", `<details><summary>${s.name} (${s.category}): ${s.passed ? "pass" : "FAIL"}${s.at ? `, ${s.at}` : ""}</summary>`, "", "```text", ...s.transcript, "```", "");
    for (const p of s.probes) out.push(`- **${p.label}**: ${p.ask} → gold "${p.gold}"; ${p.reason}${p.ttfbMs == null ? "" : ` (first bubble ${p.ttfbMs} ms)`}`);
    for (const c of s.checks) out.push(`- **${c.passed ? "pass" : "fail"}** ${c.name}: ${c.detail}`);
    out.push("", "</details>");
  }
}

writeFileSync("EVALS.md", out.join("\n") + "\n");
console.log(`EVALS.md written from ${runs.length} result file(s)`);
